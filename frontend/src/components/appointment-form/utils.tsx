// Normaliza titulos de procedimentos com acentuacao correta.
export function formatarTitulo(titulo: string): string {
  if (
    titulo.toLowerCase().includes('restauracao') ||
    titulo.toLowerCase().includes('restauração')
  ) {
    return 'Restauração de Resina';
  }
  return titulo;
}

