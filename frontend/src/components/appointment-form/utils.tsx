// Formata data ISO (YYYY-MM-DD) para exibicao amigavel em PT-BR.
export function formatarDataExibicao(dataIso: string): string {
  if (!dataIso) return '';
  const [ano, mes, dia] = dataIso.split('-');
  return `${dia}/${mes}/${ano}`;
}
